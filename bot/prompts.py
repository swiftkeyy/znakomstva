def chat_suggestions_prompt(chat_history: list, user_profile: dict, partner_profile: dict) -> str:
    history_text = "\n".join([
        f"{'Я' if msg.get('is_mine') else 'Партнёр'}: {msg.get('content', '')}"
        for msg in chat_history[-10:]
    ])
    return f"""Ты — эксперт по общению и флирту. Предложи 3 варианта ответа на последнее сообщение в переписке.

МОЙ ПРОФИЛЬ:
- Интересы: {', '.join(user_profile.get('interests', []))}

ПРОФИЛЬ ПАРТНЁРА:
- Интересы: {', '.join(partner_profile.get('interests', []))}

ИСТОРИЯ ПЕРЕПИСКИ (последние сообщения):
{history_text}

Создай 3 варианта ответа:
1. ДЕРЗКИЙ — уверенный, немного провокационный, с флиртом
2. ТЁПЛЫЙ — искренний, поддерживающий, создающий близость
3. ТРОЛЛИНГ — игривый, с лёгким подшучиванием, не обидный

ТРЕБОВАНИЯ:
- Каждый вариант органично продолжает разговор
- Учитывай контекст переписки
- Длина: 1-3 предложения
- Пиши на русском языке

Ответь СТРОГО в формате JSON:
{{
  "bold": "<дерзкий вариант>",
  "warm": "<тёплый вариант>",
  "playful": "<троллинг вариант>"
}}"""


